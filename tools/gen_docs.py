#!/usr/bin/env python3
"""Regenerate docs/API.md and docs/ERROR_CODES.md from the Go sources.

    python3 tools/gen_docs.py

Both files are derived from panel/main.go (routes) and panel/errors.go
(errCatalog), so they cannot drift from the code. Re-run after changing either.
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PANEL = ROOT / "panel"

ROUTE = re.compile(r'mux\.HandleFunc\("(GET|POST|PUT|PATCH|DELETE) "\+base\+"([^"]+)",\s*(.+)\)\s*$')
# Peer routes live in a table in peer.go: {"POST", "/api/peer/x", handleX},
PEER_ROUTE = re.compile(r'^\{"(GET|POST|PUT|PATCH|DELETE)", "(/api/peer/[^"]+)", (handle[A-Za-z0-9]+)\},$')
STATIC = ("/app.js", "/i18n-fa.js", "/tokens.css", "/fonts.css", "/base.css", "/enterprise.css",
          "/favicon.", "/apple-touch-icon.png", "/xterm", "/fonts/")


def auth_of(expr: str) -> str:
    if "requirePeerAuth" in expr:
        return "peer secret (or session)"
    if "requireRescuePeerAuth" in expr:
        return "rescue peer"
    if "requireAuth(requireCSRF" in expr:
        return "session + CSRF"
    if "requireAuth" in expr:
        return "session"
    return "none"


def handler_of(expr: str) -> str:
    names = re.findall(r"\b(handle[A-Za-z0-9]+)\b", expr)
    return names[-1] if names else ""


def gen_api() -> str:
    rows = []
    for line in (PANEL / "main.go").read_text().splitlines():
        m = ROUTE.search(line.strip())
        if not m:
            continue
        method, path, expr = m.groups()
        if path == "/" or path.startswith(STATIC):
            continue
        rows.append((path, method, auth_of(expr), handler_of(expr)))
    for line in (PANEL / "peer.go").read_text().splitlines():
        m = PEER_ROUTE.search(line.strip())
        if m:
            method, path, handler = m.groups()
            rows.append((path, method, "peer secret (or session)", handler))
    rows.sort(key=lambda r: (r[0], r[1]))
    out = [
        "# HTTP API reference",
        "",
        "> Generated by `tools/gen_docs.py` from `panel/main.go`. Do not edit by hand.",
        "",
        "Every path is served under the panel's secret base path:",
        "`http(s)://<host>:<port>/<secret>/api/...` (the secret is shown by `hashem show-panel-url`).",
        "",
        "## Authentication",
        "",
        "- **session** — log in with `POST /api/login` (`{username, password, code?}`); the reply sets the",
        "  `gre_session` cookie and a `gre_csrf` cookie.",
        "- **session + CSRF** — state-changing calls also need the CSRF token in an `X-CSRF-Token` header",
        "  (the value of the `gre_csrf` cookie).",
        "- **peer secret** — server-to-server calls between hub and spoke send the shared peer secret as",
        "  `X-Peer-Secret` or `Authorization: Bearer <secret>`. A valid admin session is accepted too.",
        "- **none** — `GET /api/health` and `POST /api/login`. `GET /metrics` is off by default and, when",
        "  enabled, needs `Authorization: Bearer <metrics token>` (see `/api/metrics-token`).",
        "",
        "Errors are JSON with a stable `E-XXXX-NN` code; see [ERROR_CODES.md](ERROR_CODES.md).",
        "Request and response bodies are defined by the handlers named below in `panel/`.",
        "",
        "## Endpoints",
        "",
        "| Method | Path | Auth | Handler |",
        "| --- | --- | --- | --- |",
    ]
    for path, method, auth, handler in rows:
        out.append(f"| `{method}` | `{path}` | {auth} | `{handler}` |")
    out.append("")
    out.append(f"Total: {len(rows)} routes.")
    out.append("")
    return "\n".join(out)


ENTRY = re.compile(
    r'"(E-[A-Z]+-\d+)":\s*\{(\d+),\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\}'
)
FAMILIES = {
    "AUTH": "Login, session, password, 2FA, CSRF",
    "SETUP": "Setup form validation",
    "PEER": "Multi-peer registry",
    "INSTALL": "Installer script",
    "ACTION": "Tunnel actions (restart, ping, remove, tune)",
    "UPDATE": "Version check, download, install, channels",
    "GRE": "GRE interface and ping diagnostics",
    "FRP": "FRP diagnostics",
    "BH": "Backhaul diagnostics",
    "SYS": "Host tooling and load",
    "WD": "Watchdog, alerts, backup",
    "SUPPORT": "Support popup",
    "RESCUE": "Connectivity rescue",
    "TERM": "In-browser terminal",
    "TLS": "Panel TLS (Let's Encrypt)",
    "PERF": "Performance tuning",
    "CARRIER": "Carrier switch",
    "ENGINE": "Engine switch",
    "SENTINEL": "Sentinel addon",
    "PATHTEST": "Path test (Benchmark tab)",
    "LIMIT": "Speed and volume limits",
}


def unescape(s: str) -> str:
    return s.replace('\\"', '"').replace("\\\\", "\\")


def gen_errors() -> str:
    seen = {}
    for m in ENTRY.finditer((PANEL / "errors.go").read_text()):
        code, status, msg, hint = m.groups()
        seen[code] = (int(status), unescape(msg), unescape(hint))
    fams = {}
    for code in seen:
        fams.setdefault(code.split("-")[1], []).append(code)
    out = [
        "# Error codes",
        "",
        "> Generated by `tools/gen_docs.py` from `panel/errors.go`. Do not edit by hand.",
        "",
        "Every backend failure carries a stable code. You see it in the UI toast, in API replies, in",
        "`GET /api/errors` (a small on-disk journal), and as an annotation on raw FRP / GRE / Backhaul log",
        "lines in the Logs tab. `HTTP 0` means the code is a log annotation, not an HTTP reply.",
        "",
    ]
    for fam in sorted(fams, key=lambda f: list(FAMILIES).index(f) if f in FAMILIES else 99):
        out += [f"## E-{fam}-xx — {FAMILIES.get(fam, fam)}", "",
                "| Code | HTTP | Meaning | What to do |", "| --- | --- | --- | --- |"]
        for code in sorted(fams[fam], key=lambda c: int(c.rsplit("-", 1)[1])):
            status, msg, hint = seen[code]
            esc = lambda t: t.replace("|", "\\|")
            out.append(f"| `{code}` | {status or '—'} | {esc(msg)} | {esc(hint)} |")
        out.append("")
    out.append(f"Total: {len(seen)} codes.")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    for name, text in (("API.md", gen_api()), ("ERROR_CODES.md", gen_errors())):
        with open(ROOT / "docs" / name, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote docs/API.md and docs/ERROR_CODES.md")
