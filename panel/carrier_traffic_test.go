func TestBackhaulCarrierEnd(t *testing.T) {
	oldLookup := carrierLookup
	carrierLookup = func(h string) string {
		if h == "hub.example" {
			return "198.51.100.7"
		}
		return ""
	}
	t.Cleanup(func() { carrierLookup = oldLookup })

	cases := []struct {
		name string
		conf string
		want []carrierEnd
	}{
		{"server listens", "[server]\nbind_addr = \"0.0.0.0:3080\"\n", []carrierEnd{{Port: 3080, UDP: true}}},
		{"server any address", "[server]\nbind_addr = \":3080\"\n", []carrierEnd{{Port: 3080, UDP: true}}},
		{"v2 listener", "[listener]\nbind_addr = \"0.0.0.0:443\"\n", []carrierEnd{{Port: 443, UDP: true}}},
		{"client dials", "[client]\nremote_addr = \"203.0.113.5:3080\"\n", []carrierEnd{{Port: 3080, Remote: "203.0.113.5", UDP: true}}},
		{"client by name", "[client]\nremote_addr = \"hub.example:3080\"\n", []carrierEnd{{Port: 3080, Remote: "198.51.100.7", UDP: true}}},
		{"name that does not resolve", "[client]\nremote_addr = \"nowhere.example:3080\"\n", nil},
		{"client dials IPv6", "[client]\nremote_addr = \"[2001:db8::1]:3080\"\n", []carrierEnd{{Port: 3080, Remote: "2001:db8::1", UDP: true}}},
		{"no port", "[client]\nremote_addr = \"203.0.113.5\"\n", nil},
	}
	for _, c := range cases {
		if got := backhaulCarrierEnd(parseBackhaulConf(c.conf)); !reflect.DeepEqual(got, c.want) {
			t.Errorf("%s: got %+v, want %+v", c.name, got, c.want)
		}
	}
}

// Every Backhaul config counts: the main one, peer and hub configs beside it,
// and the UDP companions.
func TestCarrierEndsReadsAllConfigs(t *testing.T) {
	old := backhaulDir
	backhaulDir = t.TempDir()
	t.Cleanup(func() { backhaulDir = old })
	write := func(rel, body string) {
		p := filepath.Join(backhaulDir, rel)
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("server.toml", "[server]\nbind_addr = \"0.0.0.0:3080\"\n")
	write("server-3.toml", "[server]\nbind_addr = \"0.0.0.0:3090\"\n")
	write("client-h2.toml", "[client]\nremote_addr = \"203.0.113.9:4000\"\n")
	write("udp/backhaul-udp-server.toml", "[server]\nbind_addr = \"0.0.0.0:3081\"\n")
	write("udp/dup.toml", "[server]\nbind_addr = \"0.0.0.0:3081\"\n")

	want := []carrierEnd{{Port: 3080, UDP: true, Tag: "backhaul-server"}, {Port: 3081, UDP: true, Tag: "backhaul-server"},
		{Port: 3090, UDP: true, Tag: "backhaul-server-3"}, {Port: 4000, Remote: "203.0.113.9", UDP: true, Tag: "backhaul-client-h2"}}
	if got := carrierEnds(); !reflect.DeepEqual(got, want) {
		t.Fatalf("got %+v\nwant %+v", got, want)
	}
}

func TestCarrierRules(t *testing.T) {
	got := carrierRules([]carrierEnd{{Port: 3080, UDP: true}, {Port: 22, Remote: "203.0.113.5"}}, "eth0")
	want := `*filter
:HASHEM_ACCT_IN - [0:0]
:HASHEM_ACCT_OUT - [0:0]
-F HASHEM_ACCT_IN
-F HASHEM_ACCT_OUT
-A HASHEM_ACCT_IN -i eth0 -p tcp --dport 3080
-A HASHEM_ACCT_OUT -o eth0 -p tcp --sport 3080
-A HASHEM_ACCT_IN -i eth0 -p udp --dport 3080
-A HASHEM_ACCT_OUT -o eth0 -p udp --sport 3080
-A HASHEM_ACCT_IN -i eth0 -s 203.0.113.5/32 -p tcp --sport 22
-A HASHEM_ACCT_OUT -o eth0 -d 203.0.113.5/32 -p tcp --dport 22
COMMIT
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	// No rule may have a target: the chains only count.
	for _, l := range strings.Split(got, "\n") {
		if strings.Contains(l, " -j ") {
			t.Fatalf("rule with a target: %q", l)
		}
	}
	if r := carrierRules([]carrierEnd{{Port: 1}}, ""); strings.Contains(r, " -i ") || strings.Contains(r, " -o ") {
		t.Fatalf("no interface known, yet the rules name one:\n%s", r)
	}
}

const acctSave = `# Generated by iptables-save
*filter
:INPUT ACCEPT [100:5000]
:OUTPUT ACCEPT [90:4000]
:HASHEM_ACCT_IN - [0:0]
:HASHEM_ACCT_OUT - [0:0]
[100:5000] -A INPUT -j HASHEM_ACCT_IN
[7:700] -A INPUT -i eth0 -p tcp -m tcp --dport 22 -j ACCEPT
[90:4000] -A OUTPUT -j HASHEM_ACCT_OUT
[10:1500] -A HASHEM_ACCT_IN -i eth0 -p tcp -m tcp --dport 3080
[2:200] -A HASHEM_ACCT_IN -i eth0 -p udp -m udp --dport 3080
[8:900] -A HASHEM_ACCT_OUT -o eth0 -p tcp -m tcp --sport 3080
COMMIT
`

func TestParseAcctSave(t *testing.T) {
	rx, tx, ready := parseAcctSave(acctSave)
	if rx != 1700 || tx != 900 || !ready {
		t.Fatalf("rx=%d tx=%d ready=%v, want 1700 900 true", rx, tx, ready)
	}
	// A firewall reload dropped the jump: the chains must be built again.
	noHook := strings.Replace(acctSave, "[100:5000] -A INPUT -j HASHEM_ACCT_IN\n", "", 1)
	if _, _, ready := parseAcctSave(noHook); ready {
		t.Fatal("ready without the INPUT jump")
	}
	if _, _, ready := parseAcctSave("*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n"); ready {
		t.Fatal("ready without our chains")
	}
}

// The first reading builds the chains; later readings return their counters;
// a reboot (chains gone) builds them again.
func TestReadCarrierCounters(t *testing.T) {
	oldDir, oldRunner := backhaulDir, runner
	backhaulDir = t.TempDir()
	_ = os.WriteFile(filepath.Join(backhaulDir, "server.toml"), []byte("[server]\nbind_addr = \"0.0.0.0:3080\"\n"), 0o600)
	save := "*filter\nCOMMIT\n"
	var calls []string
	runner = func(ctx context.Context, name string, args ...string) ([]byte, error) {
		calls = append(calls, name+" "+strings.Join(args, " "))
		switch name {
		case "iptables-save":
			return []byte(save), nil
		case "iptables":
			if len(args) > 2 && args[2] == "-C" {
				return nil, errors.New("no such rule")
			}
		}
		return nil, nil
	}
	reset := func() {
		carrierState.Lock()
		carrierState.at, carrierState.lastFailed = time.Time{}, time.Time{}
		carrierState.Unlock()
	}
	t.Cleanup(func() {
		backhaulDir, runner = oldDir, oldRunner
		carrierState.Lock()
		carrierState.sig, carrierState.at, carrierState.lastFailed = "", time.Time{}, time.Time{}
		carrierState.Unlock()
	})
	reset()

	if rx, tx, ok := readCarrierCounters(); !ok || rx != 0 || tx != 0 {
		t.Fatalf("first reading: %d %d %v", rx, tx, ok)
	}
	joined := strings.Join(calls, "\n")
	for _, want := range []string{"iptables-restore -w 5 -n", "iptables -w 5 -I INPUT 1 -j HASHEM_ACCT_IN", "iptables -w 5 -I OUTPUT 1 -j HASHEM_ACCT_OUT"} {
		if !strings.Contains(joined, want) {
			t.Fatalf("missing %q in:\n%s", want, joined)
		}
	}
	rules, _ := os.ReadFile(filepath.Join(configDir, "carrier-acct.v4"))
	if !strings.Contains(string(rules), "--dport 3080") {
		t.Fatalf("rules file:\n%s", rules)
	}

	// The chains exist now: the counters are read, nothing is rebuilt.
	save = acctSave
	calls = nil
	reset()
	if rx, tx, ok := readCarrierCounters(); !ok || rx != 1700 || tx != 900 {
		t.Fatalf("second reading: %d %d %v", rx, tx, ok)
	}
	if len(calls) != 1 {
		t.Fatalf("expected only iptables-save, got:\n%s", strings.Join(calls, "\n"))
	}
	// Cached for two seconds.
	calls = nil
	if _, _, ok := readCarrierCounters(); !ok || len(calls) != 0 {
		t.Fatalf("cached reading ran %v", calls)
	}

	// Reboot: the chains are gone and are built again.
	save = "*filter\nCOMMIT\n"
	calls = nil
	reset()
	if rx, _, ok := readCarrierCounters(); !ok || rx != 0 {
		t.Fatalf("after reboot: %d %v", rx, ok)
	}
	if !strings.Contains(strings.Join(calls, "\n"), "iptables-restore") {
		t.Fatal("chains not rebuilt after reboot")
	}

	// No iptables: no counters, and no retry on every tick.
	runner = func(ctx context.Context, name string, args ...string) ([]byte, error) {
		calls = append(calls, name)
		return nil, errors.New("not found")
	}
	reset()
	if _, _, ok := readCarrierCounters(); ok {
		t.Fatal("ok without iptables")
	}
	calls = nil
	carrierState.Lock()
	carrierState.at = time.Time{}
	carrierState.Unlock()
	if _, _, ok := readCarrierCounters(); ok || len(calls) != 0 {
		t.Fatalf("retried at once: %v", calls)
	}
}

// Backhaul without GRE: the chart shows the carrier ports' bytes, not zero
// and not the whole main NIC.
func TestGreTrafficCountsBackhaulPorts(t *testing.T) {
	resetTrafficState(t)
	old := carrierCounters
	t.Cleanup(func() { carrierCounters = old })
	var rx, tx uint64 = 1000, 500
	carrierCounters = func() (uint64, uint64, bool) { return rx, tx, true }
	nic := devLines(map[string][2]uint64{"lo": {5, 5}, "ens5": {500 << 30, 400 << 30}})

	greTrafficFrom(nic) // baseline
	rx, tx = 4000, 1500
	m := greTrafficFrom(nic)
	if m["down"].(uint64) != 3000 || m["up"].(uint64) != 1000 {
		t.Fatalf("down=%v up=%v, want 3000 1000", m["down"], m["up"])
	}
	// The chains were rebuilt (counters from zero): the new reading is new traffic.
	rx, tx = 200, 100
	m = greTrafficFrom(nic)
	if m["down"].(uint64) != 3200 || m["up"].(uint64) != 1100 {
		t.Fatalf("after rebuild: down=%v up=%v, want 3200 1100", m["down"], m["up"])
	}
}

// When the last tunnel goes, the chains and their jumps go too.
func TestCarrierChainsRemovedWithTunnels(t *testing.T) {
	oldDir, oldRunner := backhaulDir, runner
	backhaulDir = t.TempDir()
	var calls []string
	runner = func(ctx context.Context, name string, args ...string) ([]byte, error) {
		calls = append(calls, name+" "+strings.Join(args, " "))
		return nil, nil
	}
	t.Cleanup(func() {
		backhaulDir, runner = oldDir, oldRunner
		carrierState.Lock()
		carrierState.sig, carrierState.at = "", time.Time{}
		carrierState.Unlock()
	})
	carrierState.Lock()
	carrierState.sig, carrierState.at, carrierState.lastFailed = "old rules", time.Time{}, time.Time{}
	carrierState.Unlock()

	if _, _, ok := readCarrierCounters(); ok {
		t.Fatal("ok without tunnels")
	}
	joined := strings.Join(calls, "\n")
	for _, want := range []string{"iptables -w 5 -D INPUT -j HASHEM_ACCT_IN", "iptables -w 5 -X HASHEM_ACCT_OUT"} {
		if !strings.Contains(joined, want) {
			t.Fatalf("missing %q in:\n%s", want, joined)
		}
	}
	// Nothing left to remove: later readings run nothing.
	calls = nil
	carrierState.Lock()
	carrierState.at = time.Time{}
	carrierState.Unlock()
	readCarrierCounters()
	if len(calls) != 0 {
		t.Fatalf("ran %v", calls)
	}
}

// TestCarrierLab runs inside the hub namespace of tests/test_backhaul_udp_lab.sh
// with the real iptables and a real Backhaul tunnel: the chains are built, the
// lab's traffic script sends data through the tunnel, and the counters must
// have seen it. Then the chains are removed and must be gone.
//
//	CARRIER_LAB_DIR=<backhaul config dir> CARRIER_LAB_TRAFFIC=<script> \
//	CARRIER_LAB_MIN=<bytes each way> go test -run TestCarrierLab
func TestCarrierLab(t *testing.T) {
	dir := os.Getenv("CARRIER_LAB_DIR")
	if dir == "" {
		t.Skip("set CARRIER_LAB_DIR to run the carrier traffic lab")
	}
	minBytes, _ := strconv.ParseUint(os.Getenv("CARRIER_LAB_MIN"), 10, 64)
	oldDir, oldRunner := backhaulDir, runner
	backhaulDir, runner = dir, execRunner
	fresh := func() {
		carrierState.Lock()
		carrierState.at, carrierState.lastFailed = time.Time{}, time.Time{}
		carrierState.Unlock()
	}
	t.Cleanup(func() {
		carrierDrop()
		backhaulDir, runner = oldDir, oldRunner
		carrierState.Lock()
		carrierState.sig, carrierState.at, carrierState.lastFailed = "", time.Time{}, time.Time{}
		carrierState.Unlock()
	})
	fresh()
	if _, _, ok := readCarrierCounters(); !ok {
		t.Fatal("the chains were not built")
	}
	if out, err := exec.Command("bash", os.Getenv("CARRIER_LAB_TRAFFIC")).CombinedOutput(); err != nil {
		t.Fatalf("traffic script: %v\n%s", err, out)
	}
	fresh()
	rx, tx, ok := readCarrierCounters()
	t.Logf("carrier counters after the traffic: rx=%d tx=%d", rx, tx)
	if !ok || rx < minBytes || tx < minBytes {
		save, _ := exec.Command("iptables-save", "-c", "-t", "filter").CombinedOutput()
		t.Fatalf("rx=%d tx=%d ok=%v, want both >= %d\n%s", rx, tx, ok, minBytes, save)
	}
	// A third reading neither rebuilds the chains nor goes backwards.
	fresh()
	if rx2, tx2, _ := readCarrierCounters(); rx2 < rx || tx2 < tx {
		t.Fatalf("counters went back: %d/%d after %d/%d", rx2, tx2, rx, tx)
	}
	carrierDrop()
	if save, _ := exec.Command("iptables-save", "-t", "filter").CombinedOutput(); strings.Contains(string(save), acctIn) || strings.Contains(string(save), acctOut) {
		t.Fatalf("chains left after carrierDrop:\n%s", save)
	}
}

func TestCarrierRulesIPv6(t *testing.T) {
	old := acctIPv6
	t.Cleanup(func() { acctIPv6 = old })
	ends := []carrierEnd{{Port: 3080}, {Port: 22, Remote: "203.0.113.5"}, {Port: 3081, Remote: "2001:db8::5"}, {Port: 8443, From: "2001:db8::6"}}

	// IPv4: the IPv6 peers stay out
	if v4 := carrierRules(ends, "eth0"); strings.Contains(v4, "2001:") || !strings.Contains(v4, "-s 203.0.113.5/32") {
		t.Fatalf("IPv4 table:\n%s", v4)
	}
	// IPv6, on a server with an IPv6 address: the IPv6 peers and the port
	// listening for anyone
	acctIPv6 = func() bool { return true }
	v6 := carrierRules6(ends, "eth0")
	for _, want := range []string{
		"-A HASHEM_ACCT_IN -i eth0 -p tcp --dport 3080\n",
		"-A HASHEM_ACCT_IN -i eth0 -s 2001:db8::5/128 -p tcp --sport 3081\n",
		"-A HASHEM_ACCT_OUT -o eth0 -d 2001:db8::6/128 -p tcp --sport 8443\n",
	} {
		if !strings.Contains(v6, want) {
			t.Errorf("IPv6 table lacks %q:\n%s", want, v6)
		}
	}
	if strings.Contains(v6, "203.0.113.5") {
		t.Errorf("an IPv4 peer in the IPv6 table:\n%s", v6)
	}
	// counters of both tables land on the same ends
	if k, ok := acctRuleKey("-A HASHEM_ACCT_IN -i eth0 -s 2001:db8::5/128 -p tcp -m tcp --sport 3081", true); !ok || k != (acctKey{Port: 3081, Peer: "2001:db8::5"}) {
		t.Errorf("IPv6 rule key: %+v %v", k, ok)
	}
	// no IPv6 address and no IPv6 peer: no IPv6 table at all
	acctIPv6 = func() bool { return false }
	if r := carrierRules6([]carrierEnd{{Port: 3080}}, "eth0"); r != "" {
		t.Errorf("IPv6 table on an IPv4-only server:\n%s", r)
	}
}
